#!/usr/bin/env python3
"""Offline LeakGuard alpha kit: install, verify, smoke and verified scans."""
from __future__ import annotations
import argparse
import base64
import hashlib
from importlib import metadata
import json
import os
from pathlib import Path
import platform
import subprocess
import sys
import tempfile
import venv
import zipfile

ROOT = Path(__file__).resolve().parent

def require(ok, code):
    if not ok:
        raise ValueError(code)

def sha(path):
    with path.open('rb') as f: return hashlib.file_digest(f, 'sha256').hexdigest()

def clean_env():
    return {k: v for k, v in os.environ.items() if not k.startswith(('LEAKGUARD_', 'PYTHON', 'PIP_'))}

def run(args, *, capture=False):
    return subprocess.run([str(a) for a in args], env=clean_env(), check=True,
                          stdout=subprocess.PIPE if capture else None,
                          stderr=subprocess.PIPE if capture else None, timeout=240)

def python_at(env):
    return env / ('Scripts/python.exe' if os.name == 'nt' else 'bin/python')

def manifest():
    m = json.loads((ROOT / 'manifest.json').read_text())
    require(m['schema'] == 1, 'manifest-schema')
    require(platform.python_implementation() == 'CPython' and sys.version_info[:2] == (3, 11), 'CPython-3.11-required')
    machine = platform.machine().lower()
    target = {'Linux': 'linux', 'Darwin': 'macos', 'Windows': 'windows'}[platform.system()]
    target += '-' + ('arm64' if machine in ('arm64', 'aarch64') else 'x86_64' if machine in ('x86_64', 'amd64') else machine)
    require(target == m['target'], 'target-platform-mismatch')
    expected = set(m['files']) | {'manifest.json'}
    actual = {p.relative_to(ROOT).as_posix() for p in ROOT.rglob('*') if p.is_file()}
    require(actual == expected, 'kit-file-set-mismatch')
    for name, digest in m['files'].items():
        p = ROOT / name
        require(not Path(name).is_absolute() and '..' not in Path(name).parts and not p.is_symlink(), 'kit-path-invalid')
        require(sha(p) == digest, 'kit-file-hash-mismatch')
    return m

def config_for(env, profile):
    from leakguard_core.recognizer_profiles import compose
    return compose(profile, {'gitleaks_executable': str(ROOT / 'backend' / ('gitleaks.exe' if os.name == 'nt' else 'gitleaks')),
                             'worker_policy': 'supervised-alpha' if sys.platform == 'darwin' else 'strict',
                             'worker_memory_bytes': 2 * 1024**3})

def runtime_verify(env, m):
    require(sys.flags.isolated and Path(sys.prefix).resolve() == env, 'isolated-runtime-required')
    receipt = json.loads((env / 'kit-install.json').read_text())
    require(receipt['manifest_sha256'] == sha(ROOT / 'manifest.json'), 'runtime-kit-mismatch')
    require(receipt['python_sha256'] == sha(Path(sys.executable)), 'python-runtime-mismatch')
    wanted = {p['name'].lower().replace('_', '-'): p['version'] for p in m['packages']}
    installed = {d.metadata['Name'].lower().replace('_', '-'): d.version for d in metadata.distributions()}
    require(installed == wanted, 'installed-distribution-set-or-version-mismatch')
    # Compare installed contents with immutable wheel contents, including resource JSON,
    # native extensions, and metadata. Generated bytecode and entry-point scripts are
    # outside wheel bytes; scans invoke the checked module with isolated Python.
    for p in m['packages']:
        dist = metadata.distribution(p['name'])
        direct = dist.read_text('direct_url.json')
        require(not direct or not json.loads(direct).get('dir_info', {}).get('editable'), 'editable-install')
        with zipfile.ZipFile(ROOT / 'wheelhouse' / p['filename']) as z:
            for name in z.namelist():
                if name.endswith('/') or name.endswith('.dist-info/RECORD'):
                    continue
                parts = name.split('/')
                if parts[0].endswith('.data'):
                    require(parts[1] in ('purelib', 'platlib'), 'unsupported-wheel-data')
                    name = '/'.join(parts[2:])
                path = Path(dist.locate_file(name)).resolve()
                require(path.is_relative_to(env) and path.is_file(), 'installed-file-missing')
                require(sha(path) == hashlib.sha256(z.read('/'.join(parts))).hexdigest(), 'installed-file-hash-mismatch')
    import leakguard_core, credential_detector.plugin, presidio_detector.plugin, jose_recognizers.plugin
    for module in (leakguard_core, credential_detector.plugin, presidio_detector.plugin, jose_recognizers.plugin):
        require(Path(module.__file__).resolve().is_relative_to(env), 'source-import')
    config = json.loads((env / 'leakguard-config.json').read_text())
    require(config == config_for(env, receipt['profile']), 'profile-configuration-mismatch')
    require(credential_detector.plugin.MANIFEST.external_state == 'unknown', 'external-state-fence-missing')
    binary = Path(config['gitleaks_executable'])
    binary.chmod(0o700)
    require(run([binary, 'version'], capture=True).stdout.decode().strip().lstrip('v') == m['gitleaks_version'], 'gitleaks-version-mismatch')
    run([sys.executable, '-I', '-m', 'pip', 'check'], capture=True)
    probe = run([sys.executable, '-I', '-m', 'leakguard_core.cli', 'doctor', '--config', env / 'leakguard-config.json', '--format', 'json'], capture=True)
    require(json.loads(probe.stdout)['healthy'], 'runtime-preflight-failed')

def verify(env):
    m = manifest()
    require(env.is_dir() and python_at(env).is_file(), 'runtime-missing')
    run([python_at(env), '-I', ROOT / 'kit.py', '_runtime', '--env', env], capture=True)
    return m

def install(env, profile):
    manifest()
    require(not env.exists() and not env.is_symlink(), 'new-environment-required')
    require(not env.is_relative_to(ROOT) and not ROOT.is_relative_to(env), 'environment-outside-kit-required')
    os.umask(0o077)
    venv.EnvBuilder(with_pip=True, symlinks=os.name != 'nt').create(env)
    run([python_at(env), '-I', '-m', 'pip', 'install', '--no-index', '--no-cache-dir', '--only-binary=:all:',
         '--find-links', ROOT / 'wheelhouse', '--require-hashes', '-r', ROOT / 'requirements.lock'])
    run([python_at(env), '-I', ROOT / 'kit.py', '_configure', '--env', env, '--profile', profile], capture=True)
    verify(env)

def configure(env, profile):
    require(Path(sys.prefix).resolve() == env, 'runtime-mismatch')
    (env / 'leakguard-config.json').write_text(json.dumps(config_for(env, profile), indent=2) + '\n')
    (env / 'kit-install.json').write_text(json.dumps({'manifest_sha256': sha(ROOT / 'manifest.json'),
        'python_sha256': sha(Path(sys.executable)), 'profile': profile}, indent=2) + '\n')

def scan(env, paths, *, capture=False):
    require(paths, 'explicit-scan-path-required')
    return run([python_at(env), '-I', '-m', 'leakguard_core.cli', 'scan', '--config', env / 'leakguard-config.json',
                '--state-dir', env / 'scan-state', '--format', 'json', '--no-cache', *paths], capture=capture)

def smoke(env):
    # Temporary data and state are fresh on every invocation; no source checkout.
    with tempfile.TemporaryDirectory(prefix='leakguard-smoke-') as tmp:
        tmp = Path(tmp)
        token = '.'.join((base64.urlsafe_b64encode(b'{"alg":"dir","enc":"A256GCM"}').decode().rstrip('='), '',
                         base64.urlsafe_b64encode(b'i'*12).decode().rstrip('='),
                         base64.urlsafe_b64encode(b'synthetic').decode().rstrip('='),
                         base64.urlsafe_b64encode(b't'*16).decode().rstrip('=')))
        positive = tmp / 'positive.txt'; negative = tmp / 'negative.txt'
        positive.write_text('password=alpha-synthetic-credential\n'+token+'\n')
        negative.write_text('password=${ENV_REFERENCE}\nordinary sample text\n')
        def check(path):
            result = run([python_at(env), '-I', '-m', 'leakguard_core.cli', 'scan', '--config', env / 'leakguard-config.json',
                          '--state-dir', tmp / 'state', '--format', 'json', '--no-cache', path], capture=True)
            return json.loads(result.stdout)
        a, b = check(positive), check(negative)
        require(a['coverage']['required_complete'] and a['coverage']['enumeration_complete'] and b['coverage']['required_complete'] and b['coverage']['enumeration_complete'], 'smoke-incomplete')
        findings = [f for r in a['results'] for f in r['findings']]
        require(any(f['rule'] == 'credential-password' and f['severity'] == 'block' for f in findings), 'credential-profile-inactive')
        require(any((f.get('analysis') or {}).get('entity_type') == 'JOSE_COMPACT_JWE' and f['severity'] == 'review' for f in findings), 'jose-profile-inactive')
        require(not any(r['findings'] for r in b['results']), 'negative-smoke-failed')
        print(json.dumps({'status': 'passed', 'synthetic_only': True, 'credential_block': True, 'jose_review': True, 'negative_clean': True}))

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('command', choices=('install', 'verify', 'smoke', 'scan', '_runtime', '_configure'))
    p.add_argument('--env', type=Path, required=True)
    p.add_argument('--profile', choices=('credentials', 'sensitive', 'firm'), default='credentials')
    p.add_argument('paths', nargs='*')
    a = p.parse_intermixed_args(); env = a.env.absolute()
    try:
        if a.command == 'install': install(env, a.profile)
        elif a.command == '_configure': configure(env, a.profile)
        elif a.command == '_runtime': runtime_verify(env, manifest())
        else:
            m = verify(env)
            if a.command == 'scan': scan(env, a.paths)
            elif a.command == 'smoke': smoke(env)
            else: print(json.dumps({'status': 'passed', 'version': m['version'], 'target': m['target'], 'source_commit': m['source_commit']}))
    except (OSError, ValueError, KeyError, subprocess.SubprocessError) as e:
        # No raw subprocess output or file data in failure messages.
        print('kit-verification-failed: ' + (str(e) if isinstance(e, ValueError) else type(e).__name__), file=sys.stderr)
        return 2
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
